const PENT = [-2, 0, 3, 5, 7, 10, 12, 15, 17, 19, 22, 24];
function makeRun() {
  // 高速ペンタトニック下降ラン(クライマックス用)
  const ev = [];
  let i = PENT.length - 1 - Math.floor(Math.random() * 2);
  let g = 0;
  const span = 8 + Math.floor(Math.random() * 2);
  while (g < span && i > 1) {
    ev.push({ t: g, s: PENT[i], d: 1, a: g % 3 === 0 ? null : "h" });
    i--; g++;
  }
  ev.push({ t: g, s: PENT[i], d: Math.max(2, 12 - g), a: "v" });
  return { tags: ["run"], gen: true, ev };
}

function makeFlurry(len = 1) {
  // セクステュプレット(グリッド0.5刻み=1拍6連)の速弾きジェネレータ
  // Why Does Love Got to Be So Sad? 型のタンブリングするラン
  const gridMax = len * 12;
  const scale = PENT.filter((s) => s >= 0);
  const ev = [];
  const kind = Math.random();
  if (kind < 0.4) {
    // 3音グルーピング下降(1音ずつずらしながら転がり落ちる)
    let i = scale.length - 1 - Math.floor(Math.random() * 2);
    let t = 0;
    while (t < gridMax - 3.5 && i >= 2) {
      ev.push({ t, s: scale[i], d: 0.5 });
      ev.push({ t: t + 0.5, s: scale[i - 1], d: 0.5, a: "h" });
      ev.push({ t: t + 1, s: scale[i - 2], d: 0.5, a: "h" });
      t += 1.5; i--;
    }
    ev.push({ t, s: scale[Math.max(0, i)], d: Math.max(2, gridMax - t), a: "v" });
  } else if (kind < 0.72) {
    // 反復セルを16分で回してから解放
    const cell = pick([
      [{ s: 15, a: "b" }, { s: 12 }, { s: 10, a: "h" }, { s: 12 }],
      [{ s: 12 }, { s: 10, a: "h" }, { s: 7, a: "h" }, { s: 10 }],
      [{ s: 17 }, { s: 15, a: "h" }, { s: 12, a: "h" }, { s: 15 }],
    ]);
    let t = 0, k = 0;
    while (t < gridMax - 3) {
      const c = cell[k % cell.length];
      ev.push({ t, s: c.s, d: 0.5, a: c.a || null });
      t += 0.5; k++;
    }
    ev.push({ t, s: 10, d: gridMax - t, a: Math.random() < 0.3 ? "ub" : "bv" });
  } else {
    // 上昇フラリーからロングチョーキングへ
    let i = 2 + Math.floor(Math.random() * 2);
    let t = 0;
    while (t < gridMax - 4 && i < scale.length - 1) {
      ev.push({ t, s: scale[i], d: 0.5, a: t % 1.5 === 0 ? null : "h" });
      t += 0.5; i++;
    }
    ev.push({ t, s: scale[Math.min(i, scale.length - 1)] - 2, d: gridMax - t, a: "bv" });
  }
  return { len, tags: ["fast"], gen: true, ev };
}

function slowFastEvs(evs, gridMax) {
  // 速弾きを2/3のスピードに(0.5グリッド=6連 → 0.75グリッド=16分相当)。
  // 引き伸ばして小節からあふれた分は、元の最終音(解決音)を終端に置き直して着地させる
  const last = evs[evs.length - 1];
  let out = evs.map((e) => ({ ...e, t: e.t * 1.5, d: (e.d || 1) * 1.5 })).filter((e) => e.t <= gridMax - 0.75);
  if (out.length < evs.length) {
    const cut = gridMax - 3;
    const head = out.filter((e) => e.t < cut);
    if (head.length) out = [...head, { ...last, t: cut, d: 3 }];
  }
  out.forEach((e) => { e.d = Math.min(e.d, gridMax - e.t); });
  return out;
}

// ---------- バリエーション・エンジン ----------
// リックを素材として、スケール準拠の変形を確率的に適用して新しいフレーズを生成する
const VARY_TONES = (() => {
  const t = [];
  for (const o of [-24, -12, 0, 12, 24]) for (const d of [0, 3, 5, 7, 10]) t.push(o + d);
  t.push(-6, 6, 18); // ブルーノート
  return [...new Set(t)].filter((s) => s >= -17 && s <= 24).sort((a, b) => a - b);
})();
const snapTone = (s) => VARY_TONES.reduce((a, b) => (Math.abs(b - s) < Math.abs(a - s) ? b : a));
const stepTone = (s, dir) => {
  const i = VARY_TONES.indexOf(snapTone(s));
  return VARY_TONES[Math.max(0, Math.min(VARY_TONES.length - 1, i + dir))];
};

